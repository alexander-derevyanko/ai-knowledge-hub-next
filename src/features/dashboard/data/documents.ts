import {
  DocumentCategory,
  DocumentStatus,
  DocumentType,
  type Document,
} from '../../../shared/types/document';

type MockDocumentInput = Omit<Document, 'fileName' | 'mimeType' | 'createdAt'>;

const MIME_TYPES: Record<DocumentType, string> = {
  [DocumentType.PDF]: 'application/pdf',
  [DocumentType.DOCX]: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  [DocumentType.TXT]: 'text/plain',
  [DocumentType.MD]: 'text/markdown',
};

function createMockDocument(document: MockDocumentInput): Document {
  const extension = document.type.toLowerCase();

  return {
    ...document,
    fileName: `${document.id}.${extension}`,
    mimeType: MIME_TYPES[document.type],
    createdAt: document.updatedAt,
  };
}

